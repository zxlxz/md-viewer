/* md-viewer build: bundles the TS entry points into dist/ with esbuild and
 * copies the static assets (css/, manifest.json, options.html). The Prism
 * stylesheet is generated straight into dist/css/prism.css from the theme
 * files shipped in the installed prismjs package — no network. If those can't
 * be read, the previous build's copy is reused. */
import * as esbuild from 'esbuild';
import fs from 'node:fs';
import path from 'node:path';
// JSON import attribute — needs Node >= 22.
import themesJson from './src/prism-themes.json' with { type: 'json' };

const watch = process.argv.includes('--watch');
const PRISM_OUT = 'dist/css/prism.css';
const THEMES_DIR = 'node_modules/prismjs/themes';
// Community collection, searched after the official set (see themePath).
const COMMUNITY_THEMES_DIR = 'node_modules/prism-themes/themes';

// NOTE: the scoping parser below handles plain CSS only — a selector
// containing a quoted comma or a literal brace would be mangled. None of the
// official themes use those; re-check before adding a custom theme.

/** Theme css file for an id, searched across the installed theme packages:
 * official prismjs first, then the prism-themes collection. "default" only
 * exists in the official set; the rest are tried minified-first per dir. */
function themePath(id) {
  const names =
    id === 'default' ? ['prism.min.css'] : [`prism-${id}.min.css`, `prism-${id}.css`];
  for (const dir of [THEMES_DIR, COMMUNITY_THEMES_DIR]) {
    for (const name of names) {
      const file = path.join(dir, name);
      if (fs.existsSync(file)) return file;
    }
  }
  throw new Error(
    'no css found for theme id "' + id + '" — looked in: ' +
      [THEMES_DIR, COMMUNITY_THEMES_DIR].join(', ')
  );
}

/** Validates the theme list imported from src/prism-themes.json. */
function loadThemes() {
  if (!Array.isArray(themesJson) || !themesJson.length) {
    throw new Error('no themes found in src/prism-themes.json');
  }
  for (const t of themesJson) {
    if (!t.id || !t.name) throw new Error('theme missing id/name in src/prism-themes.json');
  }
  return themesJson;
}

/** Prefixes every selector of one stylesheet's rules with `prefix`. */
function scopeTheme(css, prefix) {
  let out = '';
  let i = 0;
  const n = css.length;
  while (i < n) {
    if (css.startsWith('/*', i)) {
      const end = css.indexOf('*/', i + 2);
      if (end === -1) break;
      out += css.slice(i, end + 2);
      i = end + 2;
      continue;
    }
    const brace = css.indexOf('{', i);
    if (brace === -1) {
      out += css.slice(i);
      break;
    }
    const selector = css.slice(i, brace).trim();
    let depth = 1;
    let j = brace + 1;
    while (j < n && depth > 0) {
      const c = css[j];
      if (c === '{') depth++;
      else if (c === '}') depth--;
      j++;
    }
    const body = css.slice(brace + 1, j - 1);
    if (selector.startsWith('@')) {
      out += selector + '{' + scopeTheme(body, prefix) + '}';
    } else {
      out += selector
        .split(',')
        .map((s) => (s.trim() ? prefix + s.trim() : s.trim()))
        .join(',');
      out += '{' + body + '}';
    }
    i = j;
  }
  return out;
}

/** Builds the full scoped stylesheet from the installed prismjs themes. */
function generatePrismCss() {
  const themes = loadThemes();
  const version = JSON.parse(
    fs.readFileSync('node_modules/prismjs/package.json', 'utf8')
  ).version;
  const parts = [
    '/* AUTO-GENERATED by build.mjs — do not edit by hand.\n' +
      ' * Theme list: src/prism-themes.json (edit it, then run `npm run gen:prism`).\n' +
      ' * Sources: PrismJS ' + version + ' + prism-themes (MIT), read from node_modules.\n' +
      ' * Each theme is scoped to html[data-md-prism="<id>"]; app.ts resolves the value from settings. */\n',
  ];
  for (const t of themes) {
    const file = themePath(t.id);
    const css = fs.readFileSync(file, 'utf8');
    if (!css.includes('.token')) {
      throw new Error('not a prism theme: ' + file);
    }
    parts.push(
      '\n/* ===== ' + t.name + ' (' + t.id + ') ===== */\n' +
        scopeTheme(css, `html[data-md-prism="${t.id}"] `)
    );
  }
  return parts.join('\n') + '\n';
}

/** Builds the article stylesheet from github-markdown-css: the three theme
 * variants scoped to our html[data-md-theme] attributes. System mode takes
 * light without a media query and dark inside prefers-color-scheme, mirroring
 * the --md-* token blocks in css/app.css (dark must come later in the file so
 * it wins the cascade when the OS is dark). */
function generateGithubCss() {
  const dir = 'node_modules/github-markdown-css';
  const version = JSON.parse(fs.readFileSync(path.join(dir, 'package.json'), 'utf8')).version;
  const read = (file) => fs.readFileSync(path.join(dir, file), 'utf8');
  const parts = [
    '/* AUTO-GENERATED by build.mjs — do not edit by hand.\n' +
      ' * Source: github-markdown-css ' + version + ' (MIT), read from node_modules.\n' +
      ' * Variants are scoped to html[data-md-theme=...] to match app.css tokens. */\n',
  ];
  const light = read('github-markdown-light.css');
  const dark = read('github-markdown-dark.css');
  for (const prefix of ['html[data-md-theme="light"] ', 'html[data-md-theme="system"] ']) {
    parts.push(scopeTheme(light, prefix));
  }
  parts.push(scopeTheme(dark, 'html[data-md-theme="dark"] '));
  parts.push(
    '@media (prefers-color-scheme: dark) {\n' +
      scopeTheme(dark, 'html[data-md-theme="system"] ') +
      '\n}'
  );
  parts.push(scopeTheme(read('github-markdown-dark-dimmed.css'), 'html[data-md-theme="dimmed"] '));
  return parts.join('\n') + '\n';
}

/** The generated stylesheets: output path + builder. All are regenerated on
 * every build; gen:prism (--prism-only) regenerates them alone. */
const GENERATED_CSS = [
  { out: 'dist/css/prism.css', generate: generatePrismCss },
  { out: 'dist/css/github-markdown.css', generate: generateGithubCss },
];

/** Regenerates every generated stylesheet. `clean` wipes dist first (full
 * builds); `fallback` reuses the previous copy when generation fails (builds
 * only — gen:prism must fail loudly instead). */
function writeGeneratedCss({ clean = false, fallback = true } = {}) {
  const previous = Object.fromEntries(
    GENERATED_CSS.map(({ out }) => [
      out,
      fallback && fs.existsSync(out) ? fs.readFileSync(out, 'utf8') : '',
    ])
  );
  if (clean) fs.rmSync('dist', { recursive: true, force: true });
  for (const { out, generate } of GENERATED_CSS) {
    try {
      fs.mkdirSync(path.dirname(out), { recursive: true });
      fs.writeFileSync(out, generate());
    } catch (err) {
      if (!fallback || !previous[out]) throw err;
      console.warn(
        'md-viewer: ' + out + ' generation failed (' + err.message + '), reusing previous copy'
      );
      fs.mkdirSync(path.dirname(out), { recursive: true });
      fs.writeFileSync(out, previous[out]);
    }
  }
}

/** Copies static assets after every (re)build so watch mode stays in sync. */
const copyStatic = {
  name: 'copy-static',
  setup(build) {
    build.onEnd(() => {
      fs.cpSync('css', 'dist/css', { recursive: true });
      fs.cpSync('manifest.json', 'dist/manifest.json');
      fs.cpSync('src/options.html', 'dist/options.html');
      // KaTeX stylesheet + all font formats referenced by its CSS fallbacks.
      const katexDist = 'node_modules/katex/dist';
      fs.cpSync(
        path.join(katexDist, 'katex.min.css'),
        'dist/katex/katex.min.css'
      );
      fs.cpSync(path.join(katexDist, 'fonts'), 'dist/katex/fonts', {
        recursive: true,
      });
    });
  },
};

const options = {
  entryPoints: ['src/detect.ts', 'src/background.ts', 'src/app.ts', 'src/options.ts'],
  outdir: 'dist',
  bundle: true,
  minify: true,
  format: 'iife',
  target: ['es2022'],
  logLevel: 'info',
  plugins: [copyStatic],
};

if (process.argv.includes('--prism-only')) {
  writeGeneratedCss({ fallback: false });
  console.log(
    'gen:prism -> ' +
      GENERATED_CSS.map(({ out }) => out).join(', ') +
      ' (' + loadThemes().length + ' prism themes)'
  );
} else if (watch) {
  // Watch rebuilds reuse whatever the generated css already holds.
  if (!fs.existsSync(PRISM_OUT)) writeGeneratedCss({ fallback: false });
  const ctx = await esbuild.context(options);
  await ctx.watch();
  console.log('md-viewer: watching for changes...');
} else {
  writeGeneratedCss({ clean: true });
  await esbuild.build(options);
}
